"""多轮对话管理：维护会话历史、识别意图、跟踪「推荐→讲解→挖需→促单」漏斗阶段。"""
import re

INTENT_KEYWORDS = [
    ("对比", ["对比", "比较", "区别", "优势", "和.*比", "哪家好", "哪个好", "不如", "好用吗", "怎么样", "值得买", "好不好"]),
    ("优惠", ["优惠", "便宜", "券", "折扣", "活动", "满减", "促销", "降价", "多少钱", "价格"]),
    ("物流", ["物流", "快递", "发货", "多久.*到", "几天.*到", "什么时候.*到", "次日达"]),
    ("售后", ["不想要", "退", "换货", "换", "售后", "保修", "质保", "坏了", "退货", "退款", "仅退款", "维修"]),
    ("参数", ["参数", "容量", "功率", "多大", "尺寸", "多少瓦", "多少升", "规格", "续航", "重量", "几档"]),
    ("使用", ["怎么用", "使用", "操作", "清洗", "糊底", "不会用", "说明书", "预约", "声音大"]),
    ("推荐", ["推荐", "买什么", "适合", "求推荐", "想买", "选哪个", "有没有", "想要", "买个", "买台", "买款", "礼物", "送礼"]),
    ("促单", ["下单", "怎么买", "链接", "拍", "付款", "买了", "现在买"]),
]

# 岗位路由：意图 → 售前/售中/售后。对应千牛人工分岗，AI 进线即自动分流，无需转接。
INTENT_POST = {
    "推荐": "售前", "对比": "售前", "参数": "售前", "使用": "售前",
    "优惠": "售中", "物流": "售中", "促单": "售中",
    "售后": "售后",
    "咨询": "售前",
}


class Conversation:
    def __init__(self):
        self.history = []  # [{"role": "user"/"assistant", "content": str}]

    def add(self, role, content):
        self.history.append({"role": role, "content": content})

    def detect_intent(self, query):
        for intent, kws in INTENT_KEYWORDS:
            for kw in kws:
                if re.search(kw, query):
                    return intent
        return "咨询"

    def post(self, query):
        """返回当前咨询应归属的客服岗位（售前/售中/售后），替代人工分流与转接。"""
        return INTENT_POST.get(self.detect_intent(query), "售前")

    def stage_hint(self, last_query):
        intent = self.detect_intent(last_query)
        hints = {
            "推荐": "当前【推荐】阶段：主动询问买家使用场景/预算/人群，为下一步【讲解】做铺垫。",
            "对比": "当前【讲解】阶段：给出差异化优势，最后引导到【促单】（结合优惠/库存）。",
            "参数": "当前【讲解】阶段：用 FAB 讲清参数带来的好处，顺势【挖需】并【促单】。",
            "使用": "当前【讲解】阶段：解决使用顾虑后，可顺势【促单】。",
            "优惠": "当前【促单】阶段：买家有购买意向，结合平台优惠果断【促单】。",
            "物流": "当前【促单】阶段：强调发货时效打消顾虑，引导下单。",
            "售后": "当前【售后】阶段：安抚情绪、给出售后方案，维护口碑（可适当挽单）。",
            "促单": "当前【促单】阶段：直接引导下单，给出清晰的下一步（优惠/链接/服务承诺）。",
        }
        return hints.get(intent, "按「推荐→讲解→挖需→促单」漏斗自然推进。")
